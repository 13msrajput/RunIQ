"""CLI: export sql/schema.sql (DDL). Add --data to also dump the current SQLite data to sql/data_dump.sql.

Usage: python -m scripts.export_sql [--data]
"""

from __future__ import annotations

import argparse  # options
import sqlite3  # iterdump gives portable INSERT statements
from pathlib import Path

from sqlalchemy.dialects import sqlite as sqlite_dialect  # compile DDL for SQLite
from sqlalchemy.schema import CreateIndex, CreateTable  # DDL constructs

from models.schema import metadata  # table definitions
from models.views import VIEW_DEFINITIONS  # view definitions
from utils.db_connection import get_engine  # engine -> file path

SQL_DIR = Path(__file__).resolve().parent.parent / "sql"  # output folder


def export_schema() -> None:
    """Write CREATE TABLE / INDEX / VIEW statements."""
    dialect = sqlite_dialect.dialect()
    lines = ["-- RunIQ schema (SQLite dialect; generated by scripts/export_sql.py)\n"]
    for table in metadata.sorted_tables:  # parents before children
        lines.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
        for index in table.indexes:
            lines.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
        lines.append("")
    for _, ddl in VIEW_DEFINITIONS:
        lines.append(" ".join(ddl.split()) + ";\n")
    (SQL_DIR / "schema.sql").write_text("\n".join(lines), encoding="utf-8")


def export_data() -> None:
    """Write INSERT statements for all rows (can be large once real data is imported)."""
    database = get_engine().url.database
    with sqlite3.connect(database) as conn, (SQL_DIR / "data_dump.sql").open(
        "w", encoding="utf-8"
    ) as out:
        for line in conn.iterdump():
            if line.startswith("INSERT"):
                out.write(line + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", action="store_true", help="also dump the data")
    args = parser.parse_args()
    export_schema()
    print("Wrote sql/schema.sql")
    if args.data:
        export_data()
        print("Wrote sql/data_dump.sql")
