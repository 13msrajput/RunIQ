def short_code(team_name: str) -> str:
    """Known code (IND) or the first three letters of the name."""
    return SHORT_CODES.get(team_name, team_name[:3].upper())


def infer_country(city: str | None, venue: str | None) -> str | None:
    """Best-effort country for a venue; ``None`` when unknown."""
    for text in (city, venue):  # try the city first, then the venue name
        if not text:
            continue
        key = text.strip().lower()
        if key in CITY_COUNTRY:  # exact city match
            return CITY_COUNTRY[key]
    if venue:  # "Wankhede Stadium, Mumbai" -> look at the part after the last comma
        tail = venue.rsplit(",", 1)[-1].strip().lower()
        if tail in CITY_COUNTRY:
            return CITY_COUNTRY[tail]
        low = venue.lower()
        for (
            known,
            country,
        ) in CITY_COUNTRY.items():  # city name appears inside the venue name
            if len(known) > 4 and known in low:
                return country
    return None


def infer_capacity(venue: str | None) -> int | None:
    """Approximate seating capacity from the static hint list (case-insensitive)."""
    if not venue:
        return None
    low = venue.lower()
    for hint, capacity in CAPACITY_HINTS:
        if hint.lower() in low:
            return capacity
    return None
